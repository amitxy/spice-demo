#!/usr/bin/env node
/**
 * Prebuild script: reads inference-config.json and emits
 * src/lib/data/inference-config.ts with the config embedded.
 * Run automatically before vite build.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const CONFIG_JSON = join(__dirname, '../../inference-config.json');
const OUTPUT_FILE = new URL('../src/lib/data/inference-config.ts', import.meta.url).pathname;

const config = JSON.parse(readFileSync(CONFIG_JSON, 'utf-8'));

mkdirSync(new URL('../src/lib/data', import.meta.url).pathname, { recursive: true });

const ts = `// Auto-generated by scripts/generate-inference-config.mjs — do not edit manually.

export interface InferenceConfig {
	thinking_prefix: string;
}

export const INFERENCE_CONFIG: InferenceConfig = ${JSON.stringify(config, null, '\t')};
`;

writeFileSync(OUTPUT_FILE, ts, 'utf-8');
console.log(`[inference-config] Generated → ${OUTPUT_FILE}`);
