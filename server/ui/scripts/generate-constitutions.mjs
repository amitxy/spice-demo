#!/usr/bin/env node
/**
 * Prebuild script: reads constitutions.json + each constitution file,
 * then emits src/lib/data/constitutions-data.ts with all content embedded.
 * Run automatically before vite build.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join, resolve } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
// Resolves to server/constitutions.json regardless of where the project is cloned
const CONSTITUTIONS_JSON = join(__dirname, '../../constitutions.json');
const OUTPUT_FILE = new URL('../src/lib/data/constitutions-data.ts', import.meta.url).pathname;
const CONSTITUTIONS_DIR = dirname(CONSTITUTIONS_JSON);

const raw = JSON.parse(readFileSync(CONSTITUTIONS_JSON, 'utf-8'));

const withContent = raw.map((c) => ({
	name: c.name,
	description: c.description,
	path: c.path,
	// Resolve constitution paths relative to constitutions.json location
	content: readFileSync(resolve(CONSTITUTIONS_DIR, c.path), 'utf-8'),
}));

mkdirSync(new URL('../src/lib/data', import.meta.url).pathname, { recursive: true });

const ts = `// Auto-generated by scripts/generate-constitutions.mjs — do not edit manually.

export interface Constitution {
	name: string;
	description: string;
	path: string;
	content: string;
}

export const CONSTITUTIONS: Constitution[] = ${JSON.stringify(withContent, null, '\t')};
`;

writeFileSync(OUTPUT_FILE, ts, 'utf-8');
console.log(`[constitutions] Generated ${withContent.length} entries → ${OUTPUT_FILE}`);
